-- Funciones puras de Core.lua y Config.lua: lo que llega de la red pasa por aquí
local addon = require("lib.addon")
local A = assert_

local HU = addon.Load({}).HU

describe("Split", function()
    it("parte por ~ y conserva los campos vacíos", function()
        A.same({ "a", "", "c", "" }, HU.Split("a~~c~", "~"))
    end)
    it("texto vacío o nil: lista vacía", function()
        A.same({}, HU.Split("", "~"))
        A.same({}, HU.Split(nil, "~"))
    end)
    it("el separador por defecto es ~", function()
        A.same({ "x", "y" }, HU.Split("x~y"))
    end)
end)

describe("SafeText", function()
    it("quita los saltos de línea y caracteres de control", function()
        A.equal("a b c", HU.SafeText("a\nb\tc"))
    end)
    it("sin enlaces permitidos, escapa todas las |", function()
        A.equal("||cffff0000rojo||r", HU.SafeText("|cffff0000rojo|r"))
    end)
    it("con enlaces, deja los de objeto y escapa los de tipo desconocido", function()
        local item = "|cff0070dd|Hitem:123::|h[Espada]|h|r"
        A.equal(item, HU.SafeText(item, true))
        A.equal("||cff0070dd||Hurl:x||h[Pincha]||h||r", HU.SafeText("|cff0070dd|Hurl:x|h[Pincha]|h|r", true))
    end)
    it("lo que no es texto da cadena vacía", function()
        A.equal("", HU.SafeText(nil))
        A.equal("", HU.SafeText(12))
    end)
end)

describe("SafeName", function()
    it("acepta un nombre normal", function() A.equal("Pepe-Garcia", HU.SafeName("Pepe-Garcia")) end)
    it("rechaza códigos y control", function()
        A.is_nil(HU.SafeName("Pe|cffpe"))
        A.is_nil(HU.SafeName("Pe\npe"))
        A.is_nil(HU.SafeName(""))
        A.is_nil(HU.SafeName(nil))
    end)
end)

describe("Momentos que llegan por la red", function()
    it("NetT: como mucho 5 min en el futuro", function()
        local now = HU.StampNow()
        A.equal(now + 300, HU.NetT(now + 9999))
        A.equal(100, HU.NetT("100.7"))
        A.is_nil(HU.NetT("x"))
        A.is_nil(HU.NetT(-1))
        A.is_nil(HU.NetT(0 / 0))
        A.is_nil(HU.NetT(math.huge))
    end)
    it("NetStamp: lo que viene de más de 5 min en el futuro no vale", function()
        local now = HU.StampNow()
        A.equal(now + 300, HU.NetStamp(now + 300))
        A.is_nil(HU.NetStamp(now + 301))
    end)
end)

describe("Utf8Cut", function()
    it("no parte una letra de dos bytes", function()
        A.equal("ma", HU.Utf8Cut("mañana", 3)) -- (ñ ocupa los bytes 3 y 4)
        A.equal("mañ", HU.Utf8Cut("mañana", 4))
    end)
end)

describe("VersionGreater", function()
    it("compara por números, no por texto", function()
        A.truthy(HU.VersionGreater("0.1.10", "0.1.9"))
        A.falsy(HU.VersionGreater("5.4.12", "5.4.12"))
        A.truthy(HU.VersionGreater("5.5", "5.4.99"))
    end)
end)

describe("ParseConfigText", function()
    it("lee hermandades, canal y título", function()
        local cfg = HU.ParseConfigText("GU:t:Mi Comunidad\nGU:c:Canal1:pass\nGU:g:Uno:AAA\nGU:g:Dos:bbb")
        A.truthy(cfg.ok)
        A.equal("Mi Comunidad", cfg.title)
        A.equal("Canal1", cfg.channel)
        A.equal("pass", cfg.password)
        A.equal(2, #cfg.guilds)
        A.equal("Dos", cfg.byTag.BBB.name) -- (la etiqueta va en mayúsculas)
    end)
    it("sin líneas GU: nil", function()
        A.is_nil(HU.ParseConfigText("Bienvenidos a la hermandad"))
    end)
    it("acepta los formatos viejos HU: y WLP:", function()
        local cfg = HU.ParseConfigText("HU:c:Canal\nWLP:g:Uno:AAA")
        A.truthy(cfg.ok)
    end)
    it("líneas pegadas en una sola", function()
        local cfg = HU.ParseConfigText("GU:c:CanalGU:g:Uno:AAA")
        A.equal("Canal", cfg.channel)
        A.equal(1, #cfg.guilds)
    end)
    it("errores: etiqueta repetida, demasiado larga, canal con símbolos", function()
        A.falsy(HU.ParseConfigText("GU:c:C\nGU:g:Uno:AAA\nGU:g:Dos:AAA").ok)
        A.falsy(HU.ParseConfigText("GU:c:C\nGU:g:Uno:ABCDEFG").ok)
        A.falsy(HU.ParseConfigText("GU:c:Can-al\nGU:g:Uno:AAA").ok)
    end)
    it("sin canal: missingChannel (llega de la nota de oficial)", function()
        local cfg = HU.ParseConfigText("GU:g:Uno:AAA")
        A.truthy(cfg.missingChannel)
        A.falsy(cfg.ok)
    end)
end)

describe("ParseChannelNote", function()
    it("canal y contraseña", function()
        local name, pass = HU.ParseChannelNote("algo GU:c:Canal:clave")
        A.equal("Canal", name)
        A.equal("clave", pass)
    end)
    it("sin contraseña", function()
        local name, pass = HU.ParseChannelNote("GU:c:Canal")
        A.equal("Canal", name)
        A.is_nil(pass)
    end)
    it("mal escrita: tercer valor true (para avisar)", function()
        local name, _, bad = HU.ParseChannelNote("GU:c:Canal:cla-ve")
        A.is_nil(name)
        A.truthy(bad)
    end)
    it("nada que ver: nil", function()
        A.is_nil(HU.ParseChannelNote("nota normal"))
        A.is_nil(HU.ParseChannelNote(nil))
    end)
end)
