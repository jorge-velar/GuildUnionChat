-- Pruebas de CARACTERIZACIÓN de la seguridad de los mensajes (Comm.lua): fijan cómo se comporta hoy
-- AllowAddonMessage, para poder pasar sus tablas al registro de mensajes (propuesta A) sin cambiar
-- nada. Si una de estas falla tras un cambio, ese cambio ha abierto o cerrado algo: hay que mirarlo.
--
-- Cada prueba fija el estado del que depende la decisión (InAnyGuild, Vouched, KnownGuildRelay...)
-- sustituyendo esas funciones: así se prueba la tabla de decisiones, no cómo se llega a ese estado.
local F = require("lib.fixtures")
local A = assert_

local a, HU
local function Allow(text, dist, sender, localID, chanName)
    local cmd, rest = text:match("^(%u%u?)~?(.*)$")
    return HU:AllowAddonMessage(cmd, sender or "Extra-Ño", HU.Split(rest, "~"), dist, localID, chanName)
end

describe("Seguridad: AllowAddonMessage", function()
    before_each(function()
        a = F.Community()
        HU = a.HU
        -- (por defecto: un desconocido, sin avalar, sin listas de las otras hermandades)
        F.Stub(HU, "InAnyGuild", false)
        F.Stub(HU, "Vouched", false)
        F.Stub(HU, "MemberOf", false)
        F.Stub(HU, "KnownGuildRelay", false)
        F.Stub(HU, "IsGuildForwarder", false)
        HU.whitelist = {}
    end)

    describe("por la hermandad (GUILD)", function()
        it("vale todo lo que no son datos de otra hermandad", function()
            A.truthy(Allow("HI~x~UNO", "GUILD"))
            A.truthy(Allow("CW~a~b", "GUILD"))
            A.truthy(Allow("ZZ~nada", "GUILD"))
        end)
        it("datos de otra hermandad sin enlace conocido: valen", function()
            A.truthy(Allow("WL~DOS~x", "GUILD"))
        end)
        it("datos de otra hermandad con enlace conocido: solo del que reparte", function()
            F.Stub(HU, "KnownGuildRelay", true)
            A.falsy(Allow("WL~DOS~x", "GUILD"))
            F.Stub(HU, "IsGuildForwarder", true)
            A.truthy(Allow("WL~DOS~x", "GUILD"))
        end)
        it("RB de otra hermandad de un compañero cualquiera: vale, pero débil", function()
            F.Stub(HU, "KnownGuildRelay", true)
            local ok, weak = Allow("RB~DOS~1~1~1~1~1~x", "GUILD")
            A.truthy(ok)
            A.truthy(weak)
        end)
        it("datos de MI hermandad por la hermandad: valen", function()
            F.Stub(HU, "KnownGuildRelay", true)
            A.truthy(Allow("WL~UNO~x", "GUILD"))
        end)
    end)

    describe("por el canal oculto (CHANNEL)", function()
        it("solo RA y LP, y solo por un canal nuestro", function()
            F.Stub(HU, "OurChannelKind", "main")
            A.truthy(Allow("RA~DOS", "CHANNEL"))
            A.truthy(Allow("LP~1", "CHANNEL"))
            A.falsy(Allow("CW~a~b", "CHANNEL"))
            A.falsy(Allow("HI~x~UNO", "CHANNEL"))
            F.Stub(HU, "OurChannelKind", nil)
            A.falsy(Allow("RA~DOS", "CHANNEL"))
        end)
    end)

    describe("otras vías", function()
        it("grupo, banda... no valen", function()
            A.falsy(Allow("HI~x~UNO", "PARTY"))
            A.falsy(Allow("HI~x~UNO", "RAID"))
            A.falsy(Allow("HI~x~UNO", "INSTANCE_CHAT"))
        end)
    end)

    describe("por susurro (WHISPER)", function()
        it("las invitaciones (GV, GA, GL, CK) valen de cualquiera", function()
            for _, c in ipairs({ "GV", "GA", "GL", "CK" }) do A.truthy(Allow(c .. "~x", "WHISPER"), c) end
        end)
        it("CW: de quien está en alguna hermandad o está avalado", function()
            A.falsy(Allow("CW~a~b", "WHISPER"))
            F.Stub(HU, "Vouched", true)
            A.truthy(Allow("CW~a~b", "WHISPER"))
            F.Stub(HU, "Vouched", false)
            F.Stub(HU, "InAnyGuild", true)
            A.truthy(Allow("CW~a~b", "WHISPER"))
        end)
        it("nadie de fuera manda datos de MI hermandad", function()
            F.Stub(HU, "InAnyGuild", true)
            F.Stub(HU, "MemberOf", true)
            A.falsy(Allow("WL~UNO~x", "WHISPER"))
            A.falsy(Allow("HI~x~UNO", "WHISPER"))
        end)

        -- RAMA MUERTA en 5.4.12: HU.whitelist no lo llena nadie (WL/WH/WD/WQ ya no se mandan ni tienen
        -- manejador). Se deja fijada para que la limpieza (propuesta G) la quite a sabiendas.
        describe("con la lista de la otra hermandad (rama muerta hoy)", function()
            before_each(function() HU.whitelist.DOS = { set = { ["extra-ño"] = true }, list = { "Extra-Ño" } } end)
            it("sus datos: solo de un miembro suyo", function()
                A.falsy(Allow("WL~DOS~x", "WHISPER"))
                F.Stub(HU, "MemberOf", true)
                A.truthy(Allow("WL~DOS~x", "WHISPER"))
            end)
            it("WH y RF: también de un avalado", function()
                F.Stub(HU, "Vouched", true)
                A.truthy(Allow("WH~DOS~x", "WHISPER"))
                A.truthy(Allow("RF~DOS", "WHISPER"))
                A.falsy(Allow("WL~DOS~x", "WHISPER"))
            end)
        end)

        describe("sin la lista de la otra hermandad (arranque)", function()
            it("saludos y listas de arranque: solo de un avalado y de una hermandad de la comunidad", function()
                A.falsy(Allow("HI~x~DOS", "WHISPER"))
                F.Stub(HU, "Vouched", true)
                A.truthy(Allow("HI~x~DOS", "WHISPER"))
                A.truthy(Allow("WL~DOS~x", "WHISPER"))
                A.falsy(Allow("HI~x~TRES", "WHISPER"), "TRES no está en la configuración")
            end)
            it("lo que no es de arranque (PB, OD...) no vale", function()
                F.Stub(HU, "Vouched", true)
                A.falsy(Allow("PB~DOS~x", "WHISPER"))
                A.falsy(Allow("OD~DOS~x", "WHISPER"))
            end)
            it("RB / RC: según quién lo manda (SenderKind) y se apunta", function()
                F.Stub(HU, "SenderKind", nil)
                A.falsy(Allow("RB~DOS~1", "WHISPER"))
                F.Stub(HU, "SenderKind", "relay")
                A.truthy(Allow("RB~DOS~1", "WHISPER"))
                A.equal("relay", HU.acceptKind.DOS[HU:Key("Extra-Ño")])
            end)
            it("RB «boot» no vale si ya me fío de la lista de esa hermandad", function()
                F.Stub(HU, "SenderKind", "boot")
                F.Stub(HU, "RosterTrusted", false)
                A.truthy(Allow("RC~DOS~1", "WHISPER"))
                F.Stub(HU, "RosterTrusted", true)
                A.falsy(Allow("RC~DOS~1", "WHISPER"))
            end)
            it("RB de una hermandad que no es de la comunidad: no", function()
                F.Stub(HU, "SenderKind", "relay")
                A.falsy(Allow("RB~TRES~1", "WHISPER"))
            end)
        end)

        describe("órdenes sin etiqueta", function()
            it("de quien está en alguna hermandad: valen", function()
                A.falsy(Allow("MU~x", "WHISPER"))
                F.Stub(HU, "InAnyGuild", true)
                A.truthy(Allow("MU~x", "WHISPER"))
            end)
            it("WQ y PL: de un avalado mientras falte alguna lista", function()
                F.Stub(HU, "Vouched", true)
                A.truthy(Allow("WQ~x", "WHISPER"))
                A.truthy(Allow("PL~x", "WHISPER"))
                A.falsy(Allow("MU~x", "WHISPER"))
                HU.whitelist.DOS = { set = {}, list = {} } -- (no pasa hoy: ver «rama muerta» arriba)
                A.falsy(Allow("WQ~x", "WHISPER"), "ya no falta ninguna lista")
            end)
        end)
    end)
end)

describe("Seguridad: recepción (OnAddonMessage)", function()
    before_each(function()
        a = F.Community()
        HU = a.HU
    end)

    it("una orden desconocida no llega a nada", function()
        a.w:Receive("HU20", "QZ~x", "GUILD", "Compi-Reino")
        A.equal(1, HU.diagRecv.QZ) -- (se cuenta, pero no hay manejador)
    end)

    it("las órdenes son 1 o 2 MAYÚSCULAS: «Q9~x» se lee como Q con «9~x»", function()
        local calls = F.Spy(HU, "Q")
        a.w:Receive("HU20", "Q9~x", "GUILD", "Compi-Reino")
        A.equal(1, #calls)
        A.same({ "9", "x" }, calls[1].f)
    end)

    it("otros prefijos no entran por aquí", function()
        local calls = F.Spy(HU, "GV")
        a.w:Receive("OTRO", "GV~x", "WHISPER", "Extra-Ño")
        A.equal(0, #calls)
    end)

    it("lo mío que vuelve no se procesa", function()
        local calls = F.Spy(HU, "CW")
        a.w:Receive("HU20", "CW~a~b", "GUILD", "Tester-Reino")
        A.equal(0, #calls)
    end)

    it("el manejador recibe remitente, campos, vía y el texto entero", function()
        local calls = F.Spy(HU, "GV")
        a.w:Receive("HU20", "GV~uno~dos", "WHISPER", "Extra-Ño")
        A.equal(1, #calls)
        A.equal("Extra-Ño", calls[1].sender)
        A.same({ "uno", "dos" }, calls[1].f)
        A.equal("WHISPER", calls[1].dist)
        A.equal("GV~uno~dos", calls[1].text)
    end)

    it("el prefijo de datos grandes (HU20B) entra igual", function()
        local calls = F.Spy(HU, "GV")
        a.w:Receive("HU20B", "GV~x", "WHISPER", "Extra-Ño")
        A.equal(1, #calls)
    end)

    it("arranque rechazado se guarda y se aplica al avalarlo (Hold / ReplayHeld)", function()
        local calls = F.Spy(HU, "HI")
        local vouched = false
        F.Stub(HU, "Vouched", function() return vouched end)
        a.w:Receive("HU20", "HI~x~DOS", "WHISPER", "Extra-Ño")
        A.equal(0, #calls, "rechazado al llegar")
        vouched = true
        HU:ReplayHeld()
        A.equal(1, #calls, "aplicado al avalarlo")
        HU:ReplayHeld()
        A.equal(1, #calls, "solo una vez")
    end)

    it("lo retenido caduca a los 3 minutos", function()
        local calls = F.Spy(HU, "HI")
        local vouched = false
        F.Stub(HU, "Vouched", function() return vouched end)
        a.w:Receive("HU20", "HI~x~DOS", "WHISPER", "Extra-Ño")
        a.w:Advance(181)
        vouched = true
        HU:ReplayHeld()
        A.equal(0, #calls)
    end)

    it("admisión: un desconocido tiene un cupo de 60 seguidos y 2 por segundo", function()
        local calls = F.Spy(HU, "GV")
        for _ = 1, 70 do a.w:Receive("HU20", "GV~x", "WHISPER", "Extra-Ño") end
        A.equal(60, #calls)
        A.equal(10, HU.diagAdmitDrop.otro)
        a.w.now = a.w.now + 1 -- (sin temporizadores: solo pasa el tiempo)
        for _ = 1, 5 do a.w:Receive("HU20", "GV~x", "WHISPER", "Extra-Ño") end
        A.equal(62, #calls)
    end)

    it("admisión: por la hermandad no hay cupo", function()
        local calls = F.Spy(HU, "ZZ")
        for _ = 1, 100 do a.w:Receive("HU20", "ZZ~x", "GUILD", "Compi-Reino") end
        A.equal(100, #calls)
    end)
end)
